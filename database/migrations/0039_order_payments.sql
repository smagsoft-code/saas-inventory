	"payment_method" text NOT NULL,
	"amount" numeric NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "order_payments_tenant_id_id_key" UNIQUE("tenant_id","id"),
	CONSTRAINT "order_payments_method_check" CHECK ("order_payments"."payment_method" IN ('cash', 'transfer', 'card', 'other')),
	CONSTRAINT "order_payments_amount_check" CHECK ("order_payments"."amount" > 0)
);
