import { Injectable } from '@nestjs/common';
import { eventOutbox } from '../../database/schema';
import type { TenantTransaction } from '../../database/tenant-context';
import type { DomainEventEnvelope } from './domain-event.contracts';

/**
 * The **single** writer of `event_outbox` in the codebase (§154 — NOTIFICATIONS owns the outbox
 * table; SALES/INVENTORY never build their own `*OutboxRepository`). Inserts exactly one row inside
 * the caller's already-open tenant transaction (`withTenantTransaction`) — it never opens its own
 * transaction, so the event and the business mutation commit or roll back together (§26, §79, §80).
 *
 * `app_tenant` has `SELECT, INSERT` on `event_outbox` (migration 0010) — no UPDATE/DELETE: claiming,
 * retrying and dead-lettering are the Event Processor's job over its own `app_event_processor`
 * connection.
 */
@Injectable()
export class OutboxRepository {
  async append(tx: TenantTransaction, envelope: DomainEventEnvelope): Promise<void> {
    await tx.insert(eventOutbox).values({
      // `id` IS the stable eventId (database.md#outbox) — generated by the publisher, carried on
      // the envelope, stored here so a redelivery resends the same identifier.
      id: envelope.eventId,
      tenantId: envelope.tenantId,
      aggregateType: envelope.aggregateType,
      aggregateId: envelope.aggregateId,
      eventType: envelope.eventType,
      payload: envelope,
      correlationId: envelope.correlationId,
      status: 'pending',
      attempts: 0,
    });
  }
}
