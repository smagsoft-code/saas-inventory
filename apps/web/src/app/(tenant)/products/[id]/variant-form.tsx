'use client';

import { useEffect, useMemo, useState, type FormEvent } from 'react';
import { useRouter } from 'next/navigation';
import { apiFetch } from '../../../../lib/api/client';
import { httpErrorMessage, isApiError } from '../../../../lib/api/errors';
import { categorySkuPrefix, suggestNextSku } from '../../../../lib/catalog/sku-suggest';
import {
  pruneAttributeValues,
  validateAttributeValues,
  type AttributeField,
} from '../../../../lib/catalog/product-attributes';
import type { AttributeOption } from '../../../../lib/types/catalog';
import { VARIANT_STATUSES, VARIANT_STATUS_LABELS, pricesAreOrdered, type Variant, type VariantStatus } from '../../../../lib/types/products';
import type { QrCode } from '../../../../lib/types/qr';
import { Alert } from '../../../../components/ui/alert';
import { Button, ButtonLink } from '../../../../components/ui/button';
import { Field } from '../../../../components/ui/field';
import { Input, Select } from '../../../../components/ui/input';
import { Spinner } from '../../../../components/ui/spinner';
import { QrCodeImage } from '../../../../components/qr-code-image';
import { ImageFilePicker } from '../../../../components/image-file-picker';
import { AttributeFields } from '../attribute-fields';

/** Mirrors `PRODUCT_IMAGE_ALLOWED_MIME_TYPES`/`PRODUCT_IMAGE_MAX_BYTES`
 * (`apps/api/src/catalog/products/product-images.service.ts`) — the same up-front client check
 * `product-form.tsx`'s create flow and `product-image-qr-panel.tsx` already use; the backend
 * re-enforces both. */
const IMAGE_ACCEPT = 'image/jpeg,image/png,image/webp';
const IMAGE_MAX_BYTES = 5 * 1024 * 1024;

/**
 * Create / edit one variant. `POST /products/:id/variants` (`VariantFieldsDto`) or
 * `PATCH /products/:id/variants/:variantId` (`UpdateVariantDto`). On edit, `sku`, `isSerialized`
 * and `isLotTracked` are **not** in the DTO — shown read-only. Prices must satisfy
 * `min ≤ base ≤ max` (same rule the DB CHECK enforces). Variant-scope attributes are governed by
 * the product's category (ADR-0026).
 *
 * Create mode mirrors `product-form.tsx`'s own create flow exactly (OUI-011 follow-up): SKU/
 * barcode suggested automatically from the *product's own, fixed* category (there is no category
 * picker here — a variant always belongs to its product's category), an image picker + auto-
 * generated QR shown in a right-hand `<aside>`, and no immediate navigation on success so that
 * panel actually renders before the caller leaves.
 */
export function VariantForm({
  mode,
  productId,
  variant,
  variantFields,
  optionsByDefinitionId,
  canViewFloor,
  canViewCost,
  totalPhysicalStock,
  categoryId,
  categoryName,
  apiPublicUrl,
}: {
  mode: 'create' | 'edit';
  productId: string;
  variant?: Variant;
  variantFields: AttributeField[];
  optionsByDefinitionId: Record<string, AttributeOption[]>;
  canViewFloor: boolean;
  canViewCost: boolean;
  /** Sum of `quantityPhysical` across every location, for the "no se puede desactivar con stock"
   * guard below — `null` when it couldn't be determined (no `inventory.view`, or the balances
   * fetch failed), in which case the guard can't run and the field just says so. Unused in
   * `mode: 'create'` (a brand-new variant has no balances yet). */
  totalPhysicalStock: number | null;
  /** The product's own category — `create` mode only, for the SKU/barcode suggestion below. There
   * is no category picker on this form (a variant can't belong to a different category than its
   * product), so this is a plain passthrough, never user-selectable here. */
  categoryId?: string;
  categoryName?: string;
  /** `create` mode only, for the auto-generated QR's `{origin}/q/:code` value. */
  apiPublicUrl?: string;
}): React.JSX.Element {
  const router = useRouter();
  const base = `/api/v1/products/${productId}/variants`;

  const [sku, setSku] = useState(variant?.sku ?? '');
  const [barcode, setBarcode] = useState(variant?.barcode ?? '');
  const [unit, setUnit] = useState(variant?.unit ?? 'unit');
  const [maxPrice, setMaxPrice] = useState(variant ? String(variant.maxPrice) : '');
  const [basePrice, setBasePrice] = useState(variant ? String(variant.basePrice) : '');
  const [minPrice, setMinPrice] = useState(
    variant && typeof variant.minPrice === 'number' ? String(variant.minPrice) : '',
  );
  const [cost, setCost] = useState(variant && typeof variant.cost === 'number' ? String(variant.cost) : '');
  const [isSerialized, setIsSerialized] = useState(variant?.isSerialized ?? false);
  const [isLotTracked, setIsLotTracked] = useState(variant?.isLotTracked ?? false);
  const [status, setStatus] = useState<VariantStatus>((variant?.status as VariantStatus) ?? 'active');
  const [attributes, setAttributes] = useState<Record<string, unknown>>(
    variant?.attributes ? { ...variant.attributes } : {},
  );

  // Create-mode only: SKU/barcode auto-suggestion (mirrors product-form.tsx exactly).
  const [skuAutoGenerated, setSkuAutoGenerated] = useState(true);
  const [barcodeAutoGenerated, setBarcodeAutoGenerated] = useState(true);
  const [skuSuggestLoading, setSkuSuggestLoading] = useState(false);

  // Create-mode only: image picker + post-create image upload + auto-generated QR.
  const [imageFile, setImageFile] = useState<File | null>(null);
  const [imagePreviewUrl, setImagePreviewUrl] = useState<string | null>(null);
  const [imageError, setImageError] = useState<string | null>(null);
  const [createdVariant, setCreatedVariant] = useState<Variant | null>(null);
  const [postCreateWarning, setPostCreateWarning] = useState<string | null>(null);
  const [qr, setQr] = useState<QrCode | null>(null);
  const [qrLoading, setQrLoading] = useState(false);
  const [qrFailed, setQrFailed] = useState(false);

  const [error, setError] = useState<string | null>(null);
  const [fieldError, setFieldError] = useState<Record<string, string>>({});
  const [attrError, setAttrError] = useState<Record<string, string>>({});
  const [success, setSuccess] = useState(false);
  const [submitting, setSubmitting] = useState(false);

  const originalAttributes = useMemo(() => JSON.stringify(variant?.attributes ?? {}), [variant]);

  // Revoke the object URL on unmount / when a new file replaces it — it is never persisted.
  useEffect(() => {
    return () => {
      if (imagePreviewUrl) URL.revokeObjectURL(imagePreviewUrl);
    };
  }, [imagePreviewUrl]);

  // Suggest a SKU once, from the product's own (fixed) category — there is no category change to
  // react to here, unlike product-form.tsx's create flow.
  useEffect(() => {
    if (mode !== 'create' || !categoryId) {
      return;
    }
    let cancelled = false;
    const prefix = categorySkuPrefix(categoryName ?? '');
    setSkuSuggestLoading(true);
    suggestNextSku(categoryId, prefix)
      .then((suggested) => {
        if (!cancelled) setSku(suggested);
      })
      .catch(() => {
        // A failed suggestion just leaves the field for the user to fill in by hand.
      })
      .finally(() => {
        if (!cancelled) setSkuSuggestLoading(false);
      });
    return () => {
      cancelled = true;
    };
  }, [mode, categoryId, categoryName]);

  // The barcode default always tracks the SKU ("COD-" + sku) until the user edits the barcode
  // itself — whether the SKU came from the suggestion above or was typed by hand.
  useEffect(() => {
    if (mode !== 'create' || !barcodeAutoGenerated) {
      return;
    }
    const expected = sku ? `COD-${sku}` : '';
    setBarcode((cur) => (cur === expected ? cur : expected));
  }, [sku, barcodeAutoGenerated, mode]);

  const dirty = useMemo(() => {
    if (mode === 'create') {
      return sku.trim().length > 0;
    }
    return (
      barcode !== (variant?.barcode ?? '') ||
      unit !== (variant?.unit ?? '') ||
      maxPrice !== String(variant?.maxPrice ?? '') ||
      basePrice !== String(variant?.basePrice ?? '') ||
      minPrice !== (typeof variant?.minPrice === 'number' ? String(variant.minPrice) : '') ||
      cost !== (typeof variant?.cost === 'number' ? String(variant.cost) : '') ||
      status !== variant?.status ||
      JSON.stringify(attributes) !== originalAttributes
    );
  }, [mode, sku, barcode, unit, maxPrice, basePrice, minPrice, cost, status, attributes, variant, originalAttributes]);

  function onPickImage(next: File | null): void {
    setImageError(null);
    if (!next) {
      setImageFile(null);
      return;
    }
    if (!IMAGE_ACCEPT.split(',').includes(next.type)) {
      setImageFile(null);
      setImageError('Solo se aceptan imágenes JPEG, PNG o WEBP.');
      return;
    }
    if (next.size > IMAGE_MAX_BYTES) {
      setImageFile(null);
      setImageError('Esa imagen supera el límite de 5 MB.');
      return;
    }
    setImagePreviewUrl((cur) => {
      if (cur) URL.revokeObjectURL(cur);
      return URL.createObjectURL(next);
    });
    setImageFile(next);
  }

  function setAttr(code: string, value: unknown): void {
    setAttributes((cur) => {
      const next = { ...cur };
      if (value === undefined) delete next[code];
      else next[code] = value;
      return next;
    });
    setSuccess(false);
  }

  function validate(): boolean {
    const next: Record<string, string> = {};
    if (mode === 'create' && (sku.trim().length < 1 || sku.trim().length > 80)) {
      next['sku'] = 'El código debe tener 1–80 caracteres.';
    }

    const priceInputs: [string, string][] = [
      ['maxPrice', maxPrice],
      ['basePrice', basePrice],
      ['minPrice', minPrice],
    ];
    for (const [key, raw] of priceInputs) {
      const requiredOnCreate = mode === 'create';
      if (raw === '') {
        if (requiredOnCreate) next[key] = 'Ingresa un precio de 0 o más.';
        continue;
      }
      if (Number.isNaN(Number(raw)) || Number(raw) < 0) {
        next[key] = 'Ingresa un precio de 0 o más.';
      }
    }
    if (cost !== '' && (Number.isNaN(Number(cost)) || Number(cost) < 0)) {
      next['cost'] = 'Ingresa un costo de 0 o más.';
    }

    // Only cross-check ordering when we actually know all three numbers.
    const haveAll = maxPrice !== '' && basePrice !== '' && minPrice !== '';
    if (haveAll && !next['maxPrice'] && !next['basePrice'] && !next['minPrice']) {
      if (!pricesAreOrdered(Number(minPrice), Number(basePrice), Number(maxPrice))) {
        next['minPrice'] = 'Los precios deben cumplir mínimo ≤ base ≤ máximo.';
      }
    }

    // "Desactivar" (reusing the existing `discontinued` status — never a new one) is only allowed
    // once physical stock is 0; a variant still holding units can't just vanish from operations
    // that read status. The backend re-checks this too (the one place every caller of this
    // endpoint goes through) — this is only the up-front UX mirror.
    if (
      mode === 'edit' &&
      status === 'discontinued' &&
      variant?.status !== 'discontinued' &&
      typeof totalPhysicalStock === 'number' &&
      totalPhysicalStock > 0
    ) {
      next['status'] =
        `No se puede desactivar: esta variante tiene ${totalPhysicalStock} unidad(es) en stock. Ajusta el stock a 0 antes de desactivarla.`;
    }

    const attrErrors = validateAttributeValues(attributes, variantFields);
    setFieldError(next);
    setAttrError(attrErrors);
    return Object.keys(next).length === 0 && Object.keys(attrErrors).length === 0;
  }

  async function handleSubmit(event: FormEvent<HTMLFormElement>): Promise<void> {
    event.preventDefault();
    if (submitting || !dirty) {
      return;
    }
    if (!validate()) {
      return;
    }
    setError(null);
    setSuccess(false);
    setSubmitting(true);
    try {
      if (mode === 'create') {
        const body: Record<string, unknown> = {
          sku: sku.trim(),
          maxPrice: Number(maxPrice),
          basePrice: Number(basePrice),
          minPrice: Number(minPrice),
          attributes: pruneAttributeValues(attributes, variantFields),
        };
        if (barcode.trim()) body['barcode'] = barcode.trim();
        if (unit.trim()) body['unit'] = unit.trim();
        if (cost !== '') body['cost'] = Number(cost);
        if (isSerialized) body['isSerialized'] = true;
        if (isLotTracked) body['isLotTracked'] = true;

        const created = await apiFetch<Variant>(base, { method: 'POST', body });
        // Deliberately no immediate `router.replace()` — the right-side panel needs to actually
        // show the uploaded image + the auto-generated QR (visualizar/imprimir) before the caller
        // navigates away, the same OUI-007 posture `product-form.tsx` already established.
        setCreatedVariant(created);
        setSubmitting(false);
        router.refresh();

        if (imageFile) {
          try {
            const imageForm = new FormData();
            imageForm.set('file', imageFile);
            imageForm.set('productVariantId', created.id);
            await apiFetch(`/api/v1/products/${productId}/images`, { method: 'POST', body: imageForm });
          } catch {
            setPostCreateWarning(
              'La variante se creó, pero no se pudo subir la imagen. Puedes intentarlo de nuevo desde esta misma página.',
            );
          }
        }

        setQrLoading(true);
        try {
          const createdQr = await apiFetch<QrCode>('/api/v1/qr-codes', {
            method: 'POST',
            body: { targetType: 'product_variant', targetId: created.id },
          });
          setQr(createdQr);
        } catch {
          setQrFailed(true);
        } finally {
          setQrLoading(false);
        }
        return;
      }

      const body: Record<string, unknown> = {};
      if (barcode !== (variant?.barcode ?? '')) body['barcode'] = barcode.trim();
      if (unit !== (variant?.unit ?? '')) body['unit'] = unit.trim();
      if (maxPrice !== String(variant?.maxPrice ?? '')) body['maxPrice'] = Number(maxPrice);
      if (basePrice !== String(variant?.basePrice ?? '')) body['basePrice'] = Number(basePrice);
      if (minPrice !== (typeof variant?.minPrice === 'number' ? String(variant.minPrice) : '') && minPrice !== '') {
        body['minPrice'] = Number(minPrice);
      }
      if (cost !== (typeof variant?.cost === 'number' ? String(variant.cost) : '') && cost !== '') {
        body['cost'] = Number(cost);
      }
      if (status !== variant?.status) body['status'] = status;
      const prunedAttrs = pruneAttributeValues(attributes, variantFields);
      if (JSON.stringify(prunedAttrs) !== originalAttributes) body['attributes'] = prunedAttrs;

      await apiFetch<Variant>(`${base}/${variant!.id}`, { method: 'PATCH', body });
      setSuccess(true);
      router.refresh();
    } catch (err) {
      setError(
        isApiError(err) && err.status === 403
          ? 'Ya no tienes permiso para hacer este cambio.'
          : httpErrorMessage(err),
      );
    } finally {
      setSubmitting(false);
    }
  }

  return (
    <div className={mode === 'create' ? 'flex flex-col gap-8 lg:flex-row lg:items-start' : undefined}>
      <form onSubmit={handleSubmit} noValidate className="flex w-full max-w-xl flex-col gap-5">
        <fieldset disabled={mode === 'create' && createdVariant !== null} className="contents">
          <Field
            label="Código"
            required={mode === 'create'}
            {...(mode === 'edit'
              ? { hint: 'No se puede cambiar.' }
              : fieldError['sku']
                ? {}
                : skuSuggestLoading
                  ? { hint: 'Sugiriendo un código para esta categoría…' }
                  : skuAutoGenerated && sku
                    ? { hint: 'Sugerido a partir de la categoría — puedes editarlo.' }
                    : {})}
            {...(fieldError['sku'] ? { error: fieldError['sku'] } : {})}
          >
            <Input
              required={mode === 'create'}
              readOnly={mode === 'edit'}
              maxLength={80}
              value={sku}
              onChange={(e) => {
                setSkuAutoGenerated(false);
                setSku(e.target.value.toUpperCase());
                setSuccess(false);
              }}
            />
          </Field>

          <div className="grid gap-4 sm:grid-cols-2">
            <Field
              label="Código de barras"
              {...(mode === 'create' && barcodeAutoGenerated && barcode
                ? { hint: 'Sugerido a partir del código — puedes editarlo.' }
                : {})}
            >
              <Input
                maxLength={80}
                value={barcode}
                onChange={(e) => {
                  setBarcodeAutoGenerated(false);
                  setBarcode(e.target.value.toUpperCase());
                  setSuccess(false);
                }}
              />
            </Field>
            <Field label="Unidad">
              <Input maxLength={20} value={unit} onChange={(e) => { setUnit(e.target.value); setSuccess(false); }} />
            </Field>
          </div>

          <div className="grid gap-4 sm:grid-cols-3">
            <Field label="Precio máximo" required={mode === 'create'} {...(fieldError['maxPrice'] ? { error: fieldError['maxPrice'] } : {})}>
              <Input type="number" min={0} step="any" value={maxPrice} onChange={(e) => { setMaxPrice(e.target.value); setSuccess(false); }} />
            </Field>
            <Field label="Precio base" required={mode === 'create'} {...(fieldError['basePrice'] ? { error: fieldError['basePrice'] } : {})}>
              <Input type="number" min={0} step="any" value={basePrice} onChange={(e) => { setBasePrice(e.target.value); setSuccess(false); }} />
            </Field>
            <Field
              label="Precio mínimo"
              required={mode === 'create'}
              hint={mode === 'edit' && !canViewFloor ? 'Oculto — déjalo en blanco para no cambiarlo.' : 'Piso antes de necesitar una aprobación.'}
              {...(fieldError['minPrice'] ? { error: fieldError['minPrice'] } : {})}
            >
              <Input type="number" min={0} step="any" value={minPrice} onChange={(e) => { setMinPrice(e.target.value); setSuccess(false); }} />
            </Field>
          </div>

          <Field
            label="Costo"
            hint={mode === 'edit' && !canViewCost ? 'Oculto — déjalo en blanco para no cambiarlo.' : 'Opcional.'}
            {...(fieldError['cost'] ? { error: fieldError['cost'] } : {})}
          >
            <Input type="number" min={0} step="any" value={cost} onChange={(e) => { setCost(e.target.value); setSuccess(false); }} />
          </Field>

          {mode === 'create' ? (
            <div className="flex flex-col gap-2">
              <label className="flex items-center gap-2 text-sm text-slate-700">
                <input type="checkbox" className="h-4 w-4 rounded border-slate-300" checked={isSerialized} onChange={(e) => setIsSerialized(e.target.checked)} />
                Serializado (cada unidad tiene su propio número de serie)
              </label>
              <label className="flex items-center gap-2 text-sm text-slate-700">
                <input type="checkbox" className="h-4 w-4 rounded border-slate-300" checked={isLotTracked} onChange={(e) => setIsLotTracked(e.target.checked)} />
                Con seguimiento de lote
              </label>
            </div>
          ) : (
            <p className="text-xs text-slate-500">
              Serializado: <span className="font-medium text-slate-700">{variant?.isSerialized ? 'sí' : 'no'}</span> · Con seguimiento de lote:{' '}
              <span className="font-medium text-slate-700">{variant?.isLotTracked ? 'sí' : 'no'}</span> (se define al crear, no se puede cambiar)
            </p>
          )}

          {mode === 'edit' && (
            <Field
              label="Estado"
              {...(fieldError['status']
                ? { error: fieldError['status'] }
                : totalPhysicalStock === null
                  ? { hint: 'No se pudo verificar el stock disponible de esta variante.' }
                  : {})}
            >
              <Select
                value={status}
                onChange={(e) => {
                  setStatus(e.target.value as VariantStatus);
                  setFieldError((cur) => (cur['status'] ? { ...cur, status: '' } : cur));
                  setSuccess(false);
                }}
              >
                {VARIANT_STATUSES.map((s) => (
                  <option key={s} value={s}>
                    {VARIANT_STATUS_LABELS[s]}
                  </option>
                ))}
              </Select>
            </Field>
          )}

          <AttributeFields
            legend="Atributos de la variante"
            fields={variantFields}
            optionsByDefinitionId={optionsByDefinitionId}
            values={attributes}
            errors={attrError}
            onChange={setAttr}
          />
        </fieldset>

        {error && <Alert tone="error">{error}</Alert>}
        {success && <Alert tone="success">Variante guardada.</Alert>}
        {postCreateWarning && <Alert tone="warning">{postCreateWarning}</Alert>}

        {mode === 'create' && createdVariant ? (
          <div className="flex flex-wrap gap-2">
            <ButtonLink href={`/products/${productId}`} className="w-fit">
              Ver producto
            </ButtonLink>
          </div>
        ) : (
          <div className="flex flex-wrap gap-2">
            <Button type="submit" loading={submitting} disabled={!dirty} className="w-fit">
              {mode === 'create' ? 'Crear variante' : 'Guardar cambios'}
            </Button>
            {mode === 'edit' && (
              <ButtonLink href={`/products/${productId}/variants/new`} variant="secondary" className="w-fit">
                Agregar variante
              </ButtonLink>
            )}
            <ButtonLink href={`/products/${productId}`} variant="ghost" className="w-fit">
              Ver producto
            </ButtonLink>
          </div>
        )}
      </form>

      {mode === 'create' && (
        <aside className="flex w-full flex-col gap-4 lg:w-72 lg:shrink-0">
          <div className="rounded-md border border-slate-200 p-4">
            <h3 className="mb-3 text-sm font-semibold text-slate-900">Imagen de la variante</h3>
            {imagePreviewUrl ? (
              <img
                src={imagePreviewUrl}
                alt=""
                className="mb-3 aspect-square w-full rounded-md border border-slate-200 object-cover"
              />
            ) : (
              <div
                className="mb-3 flex aspect-square w-full items-center justify-center rounded-md border border-dashed border-slate-300 bg-slate-50 text-slate-300"
                aria-hidden
              >
                <svg viewBox="0 0 24 24" className="h-10 w-10" fill="none" stroke="currentColor" strokeWidth={1.5}>
                  <rect x="3" y="3" width="18" height="18" rx="2" />
                  <circle cx="8.5" cy="8.5" r="1.5" />
                  <path d="M21 15l-5-5-9 9" />
                </svg>
              </div>
            )}
            <ImageFilePicker
              label="Elegir imagen"
              hint="Opcional. JPEG, PNG o WEBP, hasta 5 MB."
              accept={IMAGE_ACCEPT}
              disabled={createdVariant !== null}
              error={imageError}
              onPick={onPickImage}
            />
          </div>

          {createdVariant && (
            <div id="qr-print-area" className="rounded-md border border-slate-200 p-4">
              <h3 className="mb-3 text-sm font-semibold text-slate-900">Código QR</h3>
              {qrLoading ? (
                <p className="flex items-center gap-2 text-sm text-slate-500" aria-busy="true">
                  <Spinner className="h-4 w-4" /> Generando código QR…
                </p>
              ) : qr ? (
                <>
                  <QrCodeImage value={`${(apiPublicUrl ?? '').replace(/\/$/, '')}/q/${qr.code}`} />
                  <p className="mt-2 break-all text-xs text-slate-500">
                    {`${(apiPublicUrl ?? '').replace(/\/$/, '')}/q/${qr.code}`}
                  </p>
                  <p className="mt-1 text-sm font-medium text-slate-900">
                    Precio máximo: {Number(maxPrice).toFixed(2)}
                  </p>
                  <div className="mt-3 flex gap-2 print:hidden">
                    <Button type="button" variant="secondary" size="sm" onClick={() => window.print()}>
                      Imprimir
                    </Button>
                    <ButtonLink href="/qr" variant="ghost" size="sm">
                      Ver todos los QR
                    </ButtonLink>
                  </div>
                </>
              ) : qrFailed ? (
                <p className="text-sm text-red-700">
                  No se pudo generar el código QR automáticamente. Puedes generarlo desde la página de QR.
                </p>
              ) : null}
            </div>
          )}
        </aside>
      )}

      {mode === 'create' && (
        <style>{`
          @media print {
            body * { visibility: hidden; }
            #qr-print-area, #qr-print-area * { visibility: visible; }
            #qr-print-area { position: fixed; inset: 0; display: flex; flex-direction: column; align-items: center; justify-content: center; border: none; box-shadow: none; }
          }
        `}</style>
      )}
    </div>
  );
}
